<?php

namespace Tests\Feature;

use App\Models\LabReport;
use App\Models\Prescription;
use App\Models\User;
use Barryvdh\DomPDF\PDF;
use Dompdf\Frame;
use Illuminate\Database\Eloquent\Factories\Sequence;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Testing\TestResponse;
use PHPUnit\Framework\Attributes\TestWith;
use Tests\TestCase;

class PatientPdfExportTest extends TestCase
{
    use RefreshDatabase;

    private PDF $renderer;

    private string $renderedText = '';

    private string $renderedHtml = '';

    protected function setUp(): void
    {
        parent::setUp();

        $this->renderer = $this->app->make('dompdf.wrapper');
        $this->renderer->setCallbacks([[
            'event' => 'begin_page_render',
            'f' => function (Frame $frame): void {
                $node = $frame->get_node();
                $this->renderedText .= $node->textContent;
                $this->renderedHtml .= $node->ownerDocument->saveHTML($node);
            },
        ]]);
        $this->app->instance('dompdf.wrapper', $this->renderer);
    }

    public function test_patient_can_download_own_prescription_with_decrypted_content(): void
    {
        $patient = User::factory()->patient()->create(['name' => 'PDF Review Patient']);
        $prescription = Prescription::factory()->create([
            'patient_id' => $patient->id, 'diagnosis' => 'Seasonal Allergies',
            'instructions' => 'Take with water at night.',
        ]);

        $response = $this->actingAs($patient)->get(route('patient.prescriptions.pdf', $prescription));

        $this->assertPdfDownload($response, 'prescription-'.$prescription->id.'.pdf', 'prescription.pdf');
        $text = $this->renderedText;
        foreach (['PDF Review Patient', 'Seasonal Allergies', 'Paracetamol', '500mg', '1-0-1', '5 days', 'Take with water at night.', 'Generated by Medixa — verify authenticity with the issuing hospital'] as $expected) {
            $this->assertStringContainsString($expected, $text);
        }
        $this->assertDatabaseCount('audit_log', 0);
        $this->assertDatabaseCount('consent_tokens', 0);
    }

    public function test_patient_receives_403_for_another_patients_prescription(): void
    {
        $prescription = Prescription::factory()->create();

        $this->actingAs(User::factory()->patient()->create())
            ->get(route('patient.prescriptions.pdf', $prescription))->assertForbidden();
    }

    public function test_patient_can_preview_own_prescription_inline_using_the_export_route(): void
    {
        $patient = User::factory()->patient()->create(['name' => 'Inline Preview Patient']);
        $prescription = Prescription::factory()->create(['patient_id' => $patient->id]);

        $response = $this->actingAs($patient)->get(route('patient.prescriptions.pdf', [
            'prescription' => $prescription, 'preview' => 1,
        ]));

        $response->assertOk()->assertHeader('Content-Type', 'application/pdf');
        $this->assertStringStartsWith('inline;', $response->headers->get('Content-Disposition'));
        $this->assertStringContainsString('prescription-'.$prescription->id.'.pdf', $response->headers->get('Content-Disposition'));
        $this->assertStringStartsWith('%PDF-', $response->getContent());
        $this->assertStringContainsString('no-store', $response->headers->get('Cache-Control'));
        $this->assertStringContainsString('Inline Preview Patient', $this->renderedText);
    }

    public function test_inline_preview_enforces_the_same_ownership_check(): void
    {
        $prescription = Prescription::factory()->create();

        $this->actingAs(User::factory()->patient()->create())->get(route('patient.prescriptions.pdf', [
            'prescription' => $prescription, 'preview' => 1,
        ]))->assertForbidden();
    }

    public function test_missing_prescription_returns_404(): void
    {
        $this->actingAs(User::factory()->patient()->create())
            ->get(route('patient.prescriptions.pdf', 999999))->assertNotFound();
    }

    public function test_guests_must_log_in_for_both_exports(): void
    {
        $prescription = Prescription::factory()->create();

        $this->get(route('patient.prescriptions.pdf', $prescription))->assertRedirect(route('login'));
        $this->get(route('patient.timeline.pdf'))->assertRedirect(route('login'));
        $this->get(route('patient.prescriptions.pdf', ['prescription' => $prescription, 'preview' => 1]))
            ->assertRedirect(route('login'));
    }

    #[TestWith(['doctor'])]
    #[TestWith(['admin'])]
    #[TestWith(['receptionist'])]
    #[TestWith(['lab_assistant'])]
    public function test_other_roles_receive_403_for_both_exports(string $role): void
    {
        $prescription = Prescription::factory()->create();

        $this->actingAs(User::factory()->create(['role' => $role]))
            ->get(route('patient.prescriptions.pdf', $prescription))->assertForbidden();
        $this->get(route('patient.timeline.pdf'))->assertForbidden();
        $this->get(route('patient.prescriptions.pdf', ['prescription' => $prescription, 'preview' => 1]))
            ->assertForbidden();
    }

    public function test_timeline_pdf_contains_only_the_signed_in_patients_existing_timeline_data(): void
    {
        $this->freezeTime();
        $patient = User::factory()->patient()->create(['name' => 'Timeline Review Patient']);
        $doctor = User::factory()->doctor()->create(['name' => 'Review Doctor']);
        Prescription::factory()->create([
            'patient_id' => $patient->id, 'doctor_id' => $doctor->id,
            'diagnosis' => 'Older prescription entry', 'instructions' => 'Patient-only clinical instructions.',
            'created_at' => now()->subDays(2),
        ]);
        LabReport::factory()->create([
            'patient_id' => $patient->id, 'doctor_id' => $doctor->id,
            'report_title' => 'Newer reviewed laboratory report', 'review_status' => 'reviewed',
            'file_path' => 'reports/private-file-must-not-be-exported.pdf', 'uploaded_at' => now()->subDay(),
        ]);
        LabReport::factory()->create([
            'patient_id' => $patient->id, 'doctor_id' => $doctor->id,
            'report_title' => 'Pending laboratory upload', 'file_path' => null,
        ]);
        Prescription::factory()->create(['diagnosis' => 'Another patient private prescription']);
        LabReport::factory()->create(['report_title' => 'Another patient private report']);

        $response = $this->actingAs($patient)->get(route('patient.timeline.pdf', ['patient_id' => 999999]));

        $this->assertPdfDownload($response, 'medical-timeline.pdf', 'timeline.pdf');
        $text = $this->renderedText;
        foreach (['Timeline Review Patient', 'Dr. Review Doctor', 'Older prescription entry', 'Patient-only clinical instructions.', 'Paracetamol', 'Newer reviewed laboratory report', 'Status: Reviewed', 'Pending laboratory upload', 'Status: Awaiting laboratory upload'] as $expected) {
            $this->assertStringContainsString($expected, $text);
        }
        foreach (['Another patient private prescription', 'Another patient private report', 'private-file-must-not-be-exported.pdf'] as $excluded) {
            $this->assertStringNotContainsString($excluded, $text);
        }
        $this->assertLessThan(strpos($text, 'Older prescription entry'), strpos($text, 'Newer reviewed laboratory report'));
        $this->assertDatabaseCount('audit_log', 0);
        $this->assertDatabaseCount('consent_tokens', 0);
    }

    public function test_patient_with_no_records_can_download_an_empty_timeline(): void
    {
        $response = $this->actingAs(User::factory()->patient()->create())->get(route('patient.timeline.pdf'));

        $this->assertPdfDownload($response, 'medical-timeline.pdf');
        $this->assertStringContainsString('No medical records yet.', $this->renderedText);
    }

    public function test_pdf_escapes_patient_and_prescription_content_instead_of_loading_markup(): void
    {
        $patient = User::factory()->patient()->create(['name' => '<script>alert(1)</script>']);
        $prescription = Prescription::factory()->create([
            'patient_id' => $patient->id, 'diagnosis' => '<img src="https://example.invalid/private">',
            'instructions' => '<script>alert(2)</script>',
        ]);

        $response = $this->actingAs($patient)->get(route('patient.prescriptions.pdf', $prescription));

        $this->assertPdfDownload($response, 'prescription-'.$prescription->id.'.pdf');
        $this->assertStringNotContainsString('<script>', $this->renderedHtml);
        $this->assertStringNotContainsString('<img', $this->renderedHtml);
        $this->assertStringContainsString('<script>alert(2)</script>', $this->renderedText);
    }

    public function test_existing_timeline_has_one_export_link_and_one_link_per_own_prescription(): void
    {
        $patient = User::factory()->patient()->create();
        $prescriptions = Prescription::factory()->count(2)->create(['patient_id' => $patient->id]);
        $otherPrescription = Prescription::factory()->create();

        $response = $this->actingAs($patient)->get(route('patient.timeline'));

        $response->assertSee(route('patient.timeline.pdf'), false);
        foreach ($prescriptions as $prescription) {
            $response->assertSee(route('patient.prescriptions.pdf', $prescription), false);
            $response->assertSee('src="'.route('patient.prescriptions.pdf', ['prescription' => $prescription, 'preview' => 1]).'"', false);
        }
        $this->assertSame(2, substr_count($response->getContent(), '<iframe '));
        $response->assertDontSee(route('patient.prescriptions.pdf', $otherPrescription), false);
        $this->assertSame(3, substr_count($response->getContent(), '>Download PDF</a>'));
        if ($directory = getenv('MEDIXA_UI_REVIEW_DIRECTORY')) {
            file_put_contents($directory.DIRECTORY_SEPARATOR.'timeline.html', $response->getContent());
        }
    }

    public function test_full_timeline_exports_all_records_across_multiple_pdf_pages(): void
    {
        $patient = User::factory()->patient()->create(['name' => 'Multi Page Review Patient']);
        $doctor = User::factory()->doctor()->create();
        LabReport::factory()->count(30)->sequence(fn (Sequence $sequence): array => [
            'report_title' => 'Record number '.($sequence->index + 1),
            'uploaded_at' => now()->subDays($sequence->index),
        ])->create(['patient_id' => $patient->id, 'doctor_id' => $doctor->id]);

        $response = $this->actingAs($patient)->get(route('patient.timeline.pdf'));

        $this->assertPdfDownload($response, 'medical-timeline.pdf');
        $text = $this->renderedText;
        for ($number = 1; $number <= 30; $number++) {
            $this->assertStringContainsString('Record number '.$number, $text);
        }
        $this->assertGreaterThan(1, $this->renderer->getDomPDF()->getCanvas()->get_page_count());
    }

    private function assertPdfDownload(TestResponse $response, string $filename, ?string $reviewFilename = null): void
    {
        $response->assertOk()->assertHeader('Content-Type', 'application/pdf')->assertDownload($filename);
        $this->assertStringStartsWith('%PDF-', $response->getContent());
        $this->assertStringContainsString('%%EOF', $response->getContent());
        $this->assertStringContainsString('no-store', $response->headers->get('Cache-Control'));

        if ($reviewFilename !== null && ($directory = getenv('MEDIXA_PDF_REVIEW_DIRECTORY'))) {
            file_put_contents($directory.DIRECTORY_SEPARATOR.$reviewFilename, $response->getContent());
        }
    }
}
